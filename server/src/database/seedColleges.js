/**
 * Idempotently seeds initial colleges dataset into MongoDB
 */
export const seedInitialColleges = async () => {
  try {
    const existingCount = await College.countDocuments({ source: 'seed' });
    if (existingCount >= INITIAL_COLLEGES_DATA.length) {
      return { seeded: 0, existing: existingCount };
    }

    let seededCount = 0;
    for (const item of INITIAL_COLLEGES_DATA) {
      const normalized = normalizeCollegeName(item.name);
      const existing = await College.findOne({
        $or: [
          { normalizedName: normalized, country: item.country },
          ...(item.rorId ? [{ rorId: item.rorId }] : []),
        ],
      });

      if (!existing) {
        await College.create({
          ...item,
          normalizedName: normalized,
          logoUrl: resolveFaviconUrl(item.domain),
          logoSource: 'favicon',
          initials: item.initials || extractInitials(item.name),
        });
        seededCount++;
      }
    }

    return { seeded: seededCount, total: await College.countDocuments() };
  } catch (error) {
    console.warn('[CollegeSeeder] Warning seeding initial colleges:', error.message);
    return { seeded: 0, error: error.message };
  }
};

